function t(key, vars) {
  const lang = localStorage.getItem('lang') || 'ja';
  let str = I18N[lang]?.[key] ?? I18N['ja']?.[key] ?? key;
  if (vars) Object.entries(vars).forEach(([k, v]) => { str = str.replaceAll(`{${k}}`, v); });
  return str;
}

function applyI18n() {
  const lang = localStorage.getItem('lang') || 'ja';
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    const target = el.dataset.i18nTarget;
    const val = t(key);
    if (target === 'placeholder') el.placeholder = val;
    else if (target === 'title') el.title = val;
    else if (target === 'html') el.innerHTML = val;
    else el.textContent = val;
  });
}
